const locale = ref(localStorage.getItem('multiarena-locale') || 'zh')

export function useI18n() {
  function t(key, params) {
    let msg = messages[locale.value]?.[key] ?? messages.en[key] ?? key
    if (params) {
      Object.keys(params).forEach(k => {
        msg = msg.replace(`{${k}}`, params[k])
      })
    }
    return msg
  }

  function setLocale(lang) {
    locale.value = lang
    localStorage.setItem('multiarena-locale', lang)
  }

  const localeLabel = computed(() => locale.value === 'zh' ? 'EN' : '中')

  return { t, locale, setLocale, localeLabel }
}
